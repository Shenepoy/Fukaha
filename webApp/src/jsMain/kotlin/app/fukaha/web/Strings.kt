    fun fixerByAuthor(author: String): String = fixerByAuthorFormat.replace("%s", author)

    fun fixerPickSubtitle(platform: String): String = fixerPickSubtitleFormat.replace("%s", platform)

    fun fixerStandIn(picked: String): String = fixerStandInFormat.replace("%name", picked)

    fun embedHealthCounts(alive: Int, dead: Int, unknown: Int = 0): String = embedHealthCountsFormat
        .replace("%alive", alive.toString())
        .replace("%dead", dead.toString()) + if (unknown > 0) " · $unknown $embedHealthUnknown" else ""

    fun embedHealthProgress(done: Int, total: Int): String = embedHealthProgressFormat
        .replace("%done", done.toString())
        .replace("%total", total.toString())

    fun embedHealthCooldownToast(minutes: Int): String =
        embedHealthCooldownFormat.replace("%min", minutes.toString())

    fun previewResult(result: app.fukaha.EmbedPreviewResult): String {
        val message = when (result.outcome) {
            app.fukaha.EmbedPreviewOutcome.MetadataFound -> previewFound
            app.fukaha.EmbedPreviewOutcome.MissingMetadata -> previewMissing
            app.fukaha.EmbedPreviewOutcome.Redirected -> previewRedirected
            app.fukaha.EmbedPreviewOutcome.AccessBlocked -> previewBlocked
            app.fukaha.EmbedPreviewOutcome.HttpError -> previewHttpError
            app.fukaha.EmbedPreviewOutcome.TimedOut -> previewTimedOut
            app.fukaha.EmbedPreviewOutcome.NetworkError -> previewNetworkError
            app.fukaha.EmbedPreviewOutcome.UnsupportedContent -> previewUnsupported
            app.fukaha.EmbedPreviewOutcome.InvalidLink -> previewInvalid
        }
        return message + (result.httpStatus?.let { " (HTTP $it)" } ?: "")
    }

