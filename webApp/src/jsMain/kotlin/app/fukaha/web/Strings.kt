        fun resolveLanguage(language: AppLanguage): AppLanguage = when (language) {
            AppLanguage.System -> systemLanguage()
            else -> language
        }

        fun forLanguage(language: AppLanguage): Strings = when (resolveLanguage(language)) {
            AppLanguage.System -> EN
            AppLanguage.English -> EN
            AppLanguage.Arabic -> AR
            AppLanguage.Japanese -> JA
            AppLanguage.SimplifiedChinese -> ZH_CN
            AppLanguage.Spanish -> ES
        }

        fun languageTag(language: AppLanguage): String = when (resolveLanguage(language)) {
            AppLanguage.System -> "en"
            AppLanguage.English -> "en"
            AppLanguage.Arabic -> "ar"
            AppLanguage.Japanese -> "ja"
            AppLanguage.SimplifiedChinese -> "zh-CN"
            AppLanguage.Spanish -> "es"
        }

        fun isArabic(language: AppLanguage): Boolean =
            resolveLanguage(language) == AppLanguage.Arabic

        private fun systemLanguage(): AppLanguage =
            resolveLanguageTags(
                browserLanguageTags(window.navigator.language, window.navigator.languages),
            )
    }
